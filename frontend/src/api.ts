// 对 Wails bindings 的薄封装：组件只依赖本模块，便于测试时 mock。
// 绑定层的 Go 切片可能为 null，这里统一归一化为空数组。
import { Events } from '@wailsio/runtime';
import * as PerfService from '../bindings/unityperf/services/perfservice.js';
import type { HeavySample as WireHeavySample } from '../bindings/unityperf/services/models.js';
import type { CpuTimelineFrame, FrameData, Handshake, HeavyProfile, HeavySample, ImportProgressEvent, Report, SampleNode, Stats, Status, TickEvent } from './types';
import { normalizeSampleTree } from './lib/sample';
import type { ScreenFilmstripData } from './components/ScreenFilmstrip';

// Bindings are regenerated by Wails during the build. This local type keeps
// frontend tests usable before a developer has run the generator.
const screenService = PerfService as typeof PerfService & {
  ScreenFilmstrip: (offset: number, count: number, selected: number) => Promise<ScreenFilmstripData>;
  SetScreenCapture: (enabled: boolean) => Promise<void>;
};

function normalizeHeavySamples(samples?: (WireHeavySample | null)[] | null): HeavySample[] {
  return (samples ?? []).flatMap((sample) => sample ? [{ ...sample, children: normalizeHeavySamples(sample.children) }] : []);
}

export const api = {
  screenFilmstrip: (offset: number, count: number, selected: number) => screenService.ScreenFilmstrip(offset, count, selected),
  setScreenCapture: (enabled: boolean) => screenService.SetScreenCapture(enabled),
  connectDirect: (host: string): Promise<Handshake> => PerfService.Connect(host, 0),
  connectUSB: (serial = '', packageId = ''): Promise<Handshake> => PerfService.ConnectUSB(serial, packageId),
  disconnect: (): Promise<void> => PerfService.Disconnect(),
  status: (): Promise<Status> => PerfService.Status(),
  playerLogs: async (after: number) => await PerfService.PlayerLogs(after) ?? [],
  frames: (offset: number, limit: number): Promise<FrameData[]> =>
    PerfService.Frames(offset, limit).then((rows) => rows ?? []),
  frameAt: (index: number): Promise<FrameData> => PerfService.FrameAt(index),
  latest: (n: number): Promise<FrameData[]> => PerfService.Latest(n).then((rows) => rows ?? []),
  stats: (): Promise<Stats> => PerfService.Stats(),
  analyze: (): Promise<Report> =>
    PerfService.Analyze().then((r) => ({ ...r, issues: r.issues ?? [] }) as Report),
  clear: (): Promise<void> => PerfService.Clear(),
  setRecording: (on: boolean): Promise<void> => PerfService.SetRecording(on),
  exportCapture: (path: string): Promise<void> => PerfService.ExportCapture(path),
  exportUnityData: (path: string, editor: string): Promise<number> => PerfService.ExportUnityData(path, editor),
  importCapture: (path: string): Promise<number> => PerfService.ImportCapture(path),
  startAutoconnect: (port: number): Promise<void> => PerfService.StartAutoconnect(port),
  autoconnectAddresses: async (): Promise<string[]> => await PerfService.AutoconnectAddresses() ?? [],
  setDeepProfiling: (on: boolean): Promise<void> => PerfService.SetDeepProfiling(on),
  setCallStacks: (on: boolean): Promise<void> => PerfService.SetCallStacks(on),
  frameHierarchy: (index: number): Promise<SampleNode[]> =>
    PerfService.FrameHierarchy(index).then((rows) => normalizeSampleTree(rows)),
  frameHeavyProfile: async (start: number, end: number): Promise<HeavyProfile> => {
    const profile = await PerfService.FrameHeavyProfile(start, end);
    return {
      ...profile,
      threads: (profile.threads ?? []).map((thread) => ({
        ...thread, roots: normalizeHeavySamples(thread.roots), functions: normalizeHeavySamples(thread.functions),
      })),
    };
  },
  frameTimeline: async (index: number, frameIndex: number): Promise<CpuTimelineFrame[]> => (await PerfService.FrameTimelineContext(index, frameIndex) ?? []).map((frame) => ({
    ...frame, threads: (frame.threads ?? []).map((thread) => ({ ...thread, samples: normalizeSampleTree(thread.samples) })),
  })),
  onTick: (handler: (ev: TickEvent) => void): (() => void) =>
    Events.On('perf:tick', (ev: { data: TickEvent }) => handler(ev.data)),
  onImportProgress: (handler: (ev: ImportProgressEvent) => void): (() => void) =>
    Events.On('perf:import-progress', (ev: { data: ImportProgressEvent }) => handler(ev.data)),
};
